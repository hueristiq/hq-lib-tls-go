// CAOptions configures the self-signed CA certificate and private key produced
// by [GenerateCACertificatePrivateKey] and [GenerateCACertificatePrivateKeyPEM].
//
// Fields:
//   - CommonName (string): the Common Name (CN) for the CA certificate's
//     subject; required, with no default.
//   - Organization ([]string): the organization names for the subject; empty
//     by default.
//   - ValidFrom (time.Time): the start of the validity period; defaults to the
//     current time, backdated by 5 minutes to tolerate clock skew.
//   - ValidFor (time.Duration): the validity duration from ValidFrom; defaults
//     to 365 days and must be positive.
//   - KeyType (KeyType): the private key algorithm to generate; defaults to
//     [KeyTypeRSA2048].
type CAOptions struct {
	CommonName   string
	Organization []string
	ValidFrom    time.Time
	ValidFor     time.Duration
	KeyType      KeyType
}

// KeyType enumerates the private key algorithms supported for CA generation. Select one with
// [WithCAKeyType]; the zero value, [KeyTypeRSA2048], is used when unset.
//
// Because [CA.GenerateTLSCertificate] derives each leaf key from the CA's key,
// the KeyType chosen for the CA also determines the algorithm of every certificate it issues.
type KeyType int

const (
	// KeyTypeRSA2048 generates a 2048-bit RSA private key. This is the default and preserves
	// the behaviour of CAs generated before this option existed.
	KeyTypeRSA2048 KeyType = iota
	// KeyTypeECDSAP256 generates an ECDSA private key on the NIST P-256 curve. ECDSA keys are
	// significantly faster to generate than RSA, which benefits dynamic per-host leaf issuance.
	KeyTypeECDSAP256
	// KeyTypeEd25519 generates an Ed25519 private key.
	KeyTypeEd25519
)

// CAOptionFunc configures the CA certificate and private key generated by
// [GenerateCACertificatePrivateKey] or [GenerateCACertificatePrivateKeyPEM].
// A nil CAOptionFunc is ignored. CAOptions are applied in order, so later options
// override earlier ones. The With* helpers cover common settings, and callers
// may write custom options because [CAOptions] is exported.
//
// Parameters:
//   - opts (*CAOptions): the options to modify.
type CAOptionFunc func(opts *CAOptions)

// WithCACommonName sets the Common Name (CN) for the CA certificate's subject.
//
// The Common Name has no default and is required: generation fails if it is
// unset or empty.
func WithCACommonName(commonName string) (of CAOptionFunc) {
	return func(opts *CAOptions) {
		opts.CommonName = commonName
	}
}

// WithCAOrganization sets the Organization field for the CA certificate's subject.
//
// The default is empty: the subject carries no Organization unless this option
// is used.
func WithCAOrganization(organization []string) (of CAOptionFunc) {
	return func(opts *CAOptions) {
		opts.Organization = organization
	}
}

// WithCAValidFrom sets the start time for the CA certificate's validity period.
//
// The default is the current time. The certificate's NotBefore is backdated by
// 5 minutes from this time to tolerate clock skew between hosts.
func WithCAValidFrom(validFrom time.Time) (of CAOptionFunc) {
	return func(opts *CAOptions) {
		opts.ValidFrom = validFrom
	}
}

// WithCAValidFor sets the duration for the CA certificate's validity period.
//
// The default is 365 days. The duration must be positive: generation returns
// an error otherwise.
func WithCAValidFor(validFor time.Duration) (of CAOptionFunc) {
	return func(opts *CAOptions) {
		opts.ValidFor = validFor
	}
}

// WithCAKeyType sets the private key algorithm for the generated CA.
//
// When unset, the CA defaults to KeyTypeRSA2048. Choosing KeyTypeECDSAP256 or KeyTypeEd25519
// also makes every leaf certificate issued by the resulting CA use that algorithm, since leaf
// keys match the CA's key type.
func WithCAKeyType(keyType KeyType) (of CAOptionFunc) {
	return func(opts *CAOptions) {
		opts.KeyType = keyType
	}
}

// IssueOptions configures the leaf certificate and private key generated by
// [CA.GenerateTLSCertificate] or signed by
// [CA.SignCSR].
//
// Fields:
//   - CommonName (string): the Common Name (CN) for the subject; defaults to
//     the first host.
//   - Organization ([]string): the organization names for the subject; empty
//     by default.
//   - ValidFrom (time.Time): the start of the validity period; defaults to the
//     current time.
//   - ValidFor (time.Duration): the validity duration from ValidFrom; clamped
//     to the CA's expiry.
//   - ExtKeyUsage ([]x509.ExtKeyUsage): the extended key usages; defaults to
//     usages derived from the SAN kinds present (client authentication when
//     signing a CSR).
type IssueOptions struct {
	CommonName   string
	Organization []string
	ValidFrom    time.Time
	ValidFor     time.Duration
	ExtKeyUsage  []x509.ExtKeyUsage
}

// IssueOptionFunc configures the leaf certificate issued by
// [CA.GenerateTLSCertificate] or
// [CA.SignCSR]. A nil IssueOptionFunc is ignored. IssueOptions are
// applied in order, so later options override earlier ones. The With* helpers
// cover common settings, and callers may write custom options because
// [IssueOptions] is exported.
//
// Parameters:
//   - opts (*IssueOptions): the options to modify.
type IssueOptionFunc func(opts *IssueOptions)

// WithTLSCommonName sets the Common Name (CN) for the TLS certificate's subject.
//
// The default is the first host for
// [CA.GenerateTLSCertificate] and the CSR's Common Name for
// [CA.SignCSR]. It must not be empty.
func WithTLSCommonName(commonName string) (of IssueOptionFunc) {
	return func(opts *IssueOptions) {
		opts.CommonName = commonName
	}
}

// WithTLSOrganization sets the Organization field for the TLS certificate's subject.
//
// The default is empty for [CA.GenerateTLSCertificate] and
// the CSR's Organization for [CA.SignCSR].
func WithTLSOrganization(organization []string) (of IssueOptionFunc) {
	return func(opts *IssueOptions) {
		opts.Organization = organization
	}
}

// WithTLSValidFrom sets the start time for the TLS certificate's validity period.
//
// The default is the current time. The certificate's NotBefore is backdated by
// 5 minutes from this time to tolerate clock skew, its NotAfter is clamped
// to the CA's expiry, and a validity start at or after the CA's expiry is
// rejected.
func WithTLSValidFrom(validFrom time.Time) (of IssueOptionFunc) {
	return func(opts *IssueOptions) {
		opts.ValidFrom = validFrom
	}
}

// WithTLSValidFor sets the duration for the TLS certificate's validity period.
//
// The default is 365 days. The duration must be positive, and the resulting
// expiry is clamped to the CA's NotAfter so an issued certificate never
// outlives the authority that signed it.
func WithTLSValidFor(validFor time.Duration) (of IssueOptionFunc) {
	return func(opts *IssueOptions) {
		opts.ValidFor = validFor
	}
}

// WithTLSExtKeyUsage sets the extended key usages for the TLS certificate.
//
// When unset, the default depends on the issuing method:
// [CA.GenerateTLSCertificate] derives usages from the SAN
// kinds present — [x509.ExtKeyUsageServerAuth] when the certificate names a
// host (DNS name, IP address, or URI) and [x509.ExtKeyUsageEmailProtection]
// when it names an email address — while [CA.SignCSR]
// defaults to [x509.ExtKeyUsageClientAuth].
//
// Pass [x509.ExtKeyUsageClientAuth] explicitly to issue client certificates
// for mutual TLS.
func WithTLSExtKeyUsage(usages ...x509.ExtKeyUsage) (of IssueOptionFunc) {
	return func(opts *IssueOptions) {
		opts.ExtKeyUsage = usages
	}
}

// TLSConfigMutator configures the [crypto/tls.Config] produced by
// [CA.NewTLSConfig] and
// [CA.NewTLSConfigWithHost]. A nil TLSConfigMutator is
// ignored. Mutators are applied in order, so later mutators override earlier
// ones.
type TLSConfigMutator func(cfg *tls.Config)

// WithNextProtos sets the ALPN protocols advertised by the TLS configuration.
//
// When unset, the configuration defaults to advertising "h2" and "http/1.1", which suits HTTP
// servers. Call WithNextProtos with no arguments to disable ALPN entirely, which is
// the right choice for non-HTTP servers.
func WithNextProtos(protos ...string) (of TLSConfigMutator) {
	return func(cfg *tls.Config) {
		cfg.NextProtos = protos
	}
}

// WithAllowedHosts restricts dynamic certificate issuance to the given hostnames.
//
// Each name is normalized the same way requested SNI names are (port stripped,
// Unicode folded to lowercase, trailing dot removed), so "Example.COM." and
// "example.com" name the same host. A handshake whose SNI name is not in the
// list fails with an error before any key generation happens, which bounds the
// CPU cost of the GetCertificate hook for Internet-facing servers. A client
// that sends no SNI is unaffected: the request falls through to the wrapped
// GetCertificate, which errors ([CA.NewTLSConfig]) or
// substitutes the configured default hostname
// ([CA.NewTLSConfigWithHost]).
//
// Passing no hosts fails closed: every SNI name is rejected.
func WithAllowedHosts(hosts ...string) (of TLSConfigMutator) {
	allowed := make(map[string]struct{}, len(hosts))

	for _, host := range hosts {
		allowed[normalizeHost(host)] = struct{}{}
	}

	return func(cfg *tls.Config) {
		next := cfg.GetCertificate

		cfg.GetCertificate = func(hello *tls.ClientHelloInfo) (certificate *tls.Certificate, err error) {
			if hello == nil {
				err = hqgoerrors.New("invalid input, ClientHelloInfo is nil")

				return nil, err
			}

			if hello.ServerName != "" {
				if _, ok := allowed[normalizeHost(hello.ServerName)]; !ok {
					err = hqgoerrors.Errorf("server name %q is not in the allowed hosts list", hello.ServerName)

					return nil, err
				}
			}

			if next == nil {
				err = hqgoerrors.New("invalid input, tls.Config has no GetCertificate to wrap")

				return nil, err
			}

			return next(hello)
		}
	}
}

// Options configures a [CA], notably its optional
// certificate cache.
//
// Fields:
//   - Cache (hqgotlsauthoritycache.Cache): the cache for generated
//     certificates; nil by default, meaning certificates are regenerated per
//     request.
//   - CacheMaxAge (time.Duration): the maximum age of a cached certificate
//     before it is re-issued; defaults to 1 hour and must be positive.
type Options struct {
	Cache       hqgotlsauthoritycache.Cache
	CacheMaxAge time.Duration
}

// OptionFunc configures a [CA] created by [New] or
// [NewFromPEM]. A nil OptionFunc is ignored. Options are applied in order, so
// later options override earlier ones. The With* helpers cover common
// settings, and callers may write custom options because [Options] is
// exported.
//
// Parameters:
//   - opts (*Options): the options to modify.
type OptionFunc func(opts *Options)

// WithCacheMaxAge sets the maximum age of cached certificates before they expire.
//
// The default is 1 hour, and the age must be positive: [New] returns an error
// otherwise. It is consulted only when a cache is configured via [WithCache], and
// governs the cache used by the SNI-driven
// [CA.NewTLSConfig] path and
// [CA.TLSCertificate].
func WithCacheMaxAge(maxAge time.Duration) (of OptionFunc) {
	return func(opts *Options) {
		opts.CacheMaxAge = maxAge
	}
}

// WithCache sets the certificate cache used to store dynamically generated certificates.
//
// Caching is opt-in: when unset (nil), certificates are regenerated per request. The cache
// stores certificates keyed by normalized hostname and is consulted by the SNI-driven
// [CA.NewTLSConfig] path and [CA.TLSCertificate];
// see [hqgotlsauthoritycache.NewInMemory] for a ready-made implementation.
func WithCache(c hqgotlsauthoritycache.Cache) (of OptionFunc) {
	return func(opts *Options) {
		opts.Cache = c
	}
}

// New initializes a new CA with the provided CA certificate and private key.
//
// It verifies that the certificate is configured as a CA with valid basic constraints, is within
// its validity period, has the necessary key usage for certificate signing, and that the private
// key matches the certificate's public key (RSA, ECDSA, or Ed25519).
// Caching of issued certificates is opt-in via [WithCache]; the cache maximum age defaults
// to 1 hour and can be overridden via [WithCacheMaxAge].
//
// Parameters:
//   - caCertificate (*x509.Certificate): a pointer to the X.509 CA certificate.
//   - caPrivateKey (crypto.Signer): the private key corresponding to the CA certificate, implementing crypto.Signer.
//   - ofs (...OptionFunc): a variadic list of options to configure the certificate cache.
//
// Returns:
//   - ca (*CA): a pointer to the initialized CA.
//   - err (error): an error if the CA certificate or private key is invalid, mismatched, or incompatible; otherwise, nil.
