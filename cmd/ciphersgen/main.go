// Command ciphersgen regenerates the cipher-classification table from the
// ciphersuite.info dataset. By default it writes a standalone file (or stdout);
// with -inplace it replaces the marked section inside ciphers.go:
//
//	go generate ./...
//	cd cmd/ciphersgen && go run . -inplace -output ../../ciphers.go
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"
)

// datasetURL is the ciphersuite.info API endpoint.
const datasetURL = "https://ciphersuite.info/api/cs/"

const (
	// sectionBegin marks the start of the generated table in an in-place
	// target file.
	sectionBegin = "// BEGIN GENERATED CIPHER CLASSIFICATION"
	// sectionEnd marks the end of the generated table in an in-place target
	// file.
	sectionEnd = "// END GENERATED CIPHER CLASSIFICATION"
)

// apiResponse is the shape of the ciphersuite.info response: a list of
// single-entry objects keyed by suite name.
type apiResponse struct {
	Ciphersuites []map[string]cipherSuite `json:"ciphersuites"`
}

// cipherSuite is one entry of the dataset.
type cipherSuite struct {
	HexByte1 string `json:"hex_byte_1"`
	HexByte2 string `json:"hex_byte_2"`
	Security string `json:"security"`
}

// securityRank maps the dataset's security labels to the client package's
// CipherSecurity constants.
var securityRank = map[string]int{
	"insecure":    0,
	"weak":        1,
	"secure":      2,
	"recommended": 3,
}

// securityNames renders the rank back to the constant name.
var securityNames = map[int]string{
	0: "CipherSecurityInsecure",
	1: "CipherSecurityWeak",
	2: "CipherSecuritySecure",
	3: "CipherSecurityRecommended",
}

func main() {
	output := flag.String("output", "", "write the generated table to this path instead of stdout")
	inplace := flag.Bool("inplace", false, "replace the marked section in -output instead of writing a standalone file")

	flag.Parse()

	if *inplace && *output == "" {
		fatalf("-inplace requires -output")
	}

	section := generateSection()

	if *inplace {
		if err := replaceSection(*output, section); err != nil {
			fatalf("updating %s: %v", *output, err)
		}

		return
	}

	writer := io.Writer(os.Stdout)

	if *output != "" {
		file, err := os.Create(*output)
		if err != nil {
			fatalf("creating output file %s: %v", *output, err)
		}

		defer func() {
			_ = file.Close()
		}()

		writer = file
	}

	_, _ = fmt.Fprintf(writer, "package tls\n\n%s", section)
}

// generateSection fetches the dataset and renders the generated comment and
// cipher-classification map.
func generateSection() (section []byte) {
	client := &http.Client{
		Timeout: 30 * time.Second,
	}

	request, err := http.NewRequestWithContext(context.Background(), http.MethodGet, datasetURL, http.NoBody)
	if err != nil {
		fatalf("building request for %s: %v", datasetURL, err)
	}

	response, err := client.Do(request)
	if err != nil {
		fatalf("fetching %s: %v", datasetURL, err)
	}

	defer func() {
		_ = response.Body.Close()
	}()

	var api apiResponse

	if err = json.NewDecoder(response.Body).Decode(&api); err != nil {
		fatalf("decoding response: %v", err)
	}

	type entry struct {
		id   uint16
		rank int
	}

	entries := make([]entry, 0, len(api.Ciphersuites))

	for _, named := range api.Ciphersuites {
		for _, suite := range named {
			high, highErr := strconv.ParseUint(strings.TrimPrefix(suite.HexByte1, "0x"), 16, 8)
			low, lowErr := strconv.ParseUint(strings.TrimPrefix(suite.HexByte2, "0x"), 16, 8)
			rank, ok := securityRank[suite.Security]

			if highErr != nil || lowErr != nil || !ok {
				continue
			}

			entries = append(entries, entry{
				id:   uint16(high)<<8 | uint16(low),
				rank: rank,
			})
		}
	}

	sort.Slice(entries, func(i, j int) bool {
		return entries[i].id < entries[j].id
	})

	var buffer bytes.Buffer

	write := func(line string) {
		_, _ = fmt.Fprintln(&buffer, line)
	}

	write("// Code generated by go run ./cmd/ciphersgen; DO NOT EDIT.")
	write("//")
	write("// Source: https://ciphersuite.info — the ciphersuite.info dataset.")
	write("// Regenerate from the repository root with:")
	write("//")
	write("//\tgo generate ./...")
	write("//")
	write("// cipherClassification maps cipher suite IDs to their security")
	write("// classification.")
	write("var cipherClassification = map[uint16]CipherSecurity{")

	for _, item := range entries {
		_, _ = fmt.Fprintf(&buffer, "\t%#04x: %s,\n", item.id, securityNames[item.rank])
	}

	write("}\n")

	return buffer.Bytes()
}

// replaceSection replaces the text between the generated-section markers in
// path with section, preserving the rest of the file.
func replaceSection(path string, section []byte) (err error) {
	data, err := os.ReadFile(path) //nolint:gosec // the output path is supplied explicitly by the maintainer.
	if err != nil {
		return err
	}

	begin := bytes.Index(data, []byte(sectionBegin))
	if begin < 0 {
		return fmt.Errorf("begin marker %q not found", sectionBegin)
	}

	contentStart := begin + len(sectionBegin)

	endOffset := bytes.Index(data[contentStart:], []byte(sectionEnd))
	if endOffset < 0 {
		return fmt.Errorf("end marker %q not found", sectionEnd)
	}

	contentEnd := contentStart + endOffset

	var buffer bytes.Buffer

	buffer.Write(data[:contentStart])
	buffer.WriteByte('\n')
	buffer.Write(section)
	buffer.Write(data[contentEnd:])

	dir := filepath.Dir(path)

	temp, err := os.CreateTemp(dir, ".ciphersgen-*.go")
	if err != nil {
		return err
	}

	tempName := temp.Name()

	defer func() {
		if err != nil {
			_ = os.Remove(tempName)
		}
	}()

	if _, err = temp.Write(buffer.Bytes()); err != nil {
		_ = temp.Close()

		return err
	}

	if err = temp.Chmod(0o644); err != nil {
		_ = temp.Close()

		return err
	}

	if closeErr := temp.Close(); closeErr != nil {
		return closeErr
	}

	if renameErr := os.Rename(tempName, path); renameErr != nil {
		return renameErr
	}

	return nil
}

// fatalf prints the error to stderr and exits non-zero.
//
// Parameters:
//   - format (string): a fmt-style format string; the message is prefixed with "gen: ".
//   - args (...any): values for the format string's verbs.
func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen: "+format+"\n", args...)

	os.Exit(1)
}
